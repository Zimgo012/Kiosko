        Text(
            text = "Rollie Photo Booth",
            style = MaterialTheme.typography.headlineLarge
        )
        Spacer(modifier = Modifier.height(32.dp))
        Button(onClick = onStartCamera) {
            Text(text = "Start Photo Booth")
        }
    }
}
